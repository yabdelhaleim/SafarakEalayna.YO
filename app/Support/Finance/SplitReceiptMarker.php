<?php

namespace App\Support\Finance;

/**
 * علامة ربط شقّي السند قبض المجزّأ (Phase 9 — 2026-11-03).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * لماذا هذه العلامة؟
 *
 * سند قبض الطيران الذي يحتوي فائضاً يُقسَّم في Phase 9 إلى قيدين:
 *
 *   ① شق الإيراد المحقق  (type = 'income')  → يحمل تخصيصات الحجوزات.
 *   ② شق الأمانات/الفائض (type = 'transfer') → التزام في الميزانية (Customer
 *                                            Deposit / Liability) وليس إيراداً.
 *
 * القيدان معاً يكوّنان "سنداً واحداً" من الناحية المحاسبية: يجب أن يُلغيا
 * معاً عند إلغاء السند (وإلا بقيت جهة واحدة مختلة في دفتر الأستاذ ودفتر
 * الرصيد الدائن).
 *
 * لكن `transactions` لا تملك عموداً مخصصاً للربط (related_type/related_id
 * زوج واحد فقط، وقد استُهلك لـ Customer::class لأن خدمة التخصيص تشترطه)،
 * لذلك تُوسم ملاحظات شق الأمانات بعلامة تحمل معرّف شق الإيراد:
 *
 *     … [سند مجزأ #123]
 *
 * وبها يستطيع أي مستهلك أن يحل مجموعة السند في الاتجاهين:
 *   • من شق الإيراد  → البحث عن شق الأمانات بالعلامة.
 *   • من شق الأمانات → قراءة المعرّف من العلامة (بحث بمعرّف = دقيق).
 *
 * ملاحظة: العلامة في *نهاية* الملاحظات، حتى يظل بادئة "عكس:" (اصطلاح
 * عكس المعاملات في المشروع) في أول الملاحظات فتبقى كل أدوات كشف العكس
 * تعمل كما هي.
 */
final class SplitReceiptMarker
{
    /**
     * قالب العلامة (بدون معرّف).
     */
    public const TEMPLATE = '[سند مجزأ #%d]';

    /**
     * نمط استخراج المعرّف من الملاحظات.
     */
    private const PATTERN = '/\[سند مجزأ #(\d+)\]/u';

    /**
     * يبني نص العلامة لمعرّف شق الإيراد.
     */
    public static function stamp(int $anchorId): string
    {
        return sprintf(self::TEMPLATE, $anchorId);
    }

    /**
     * يستخرج معرّف شق الإيراد من الملاحظات (أو null إن لم تكن موسومة).
     */
    public static function extract(?string $notes): ?int
    {
        if (! is_string($notes) || $notes === '') {
            return null;
        }

        if (preg_match(self::PATTERN, $notes, $matches) !== 1) {
            return null;
        }

        return (int) $matches[1];
    }

    /**
     * نمط LIKE للبحث عن شق الأمانات المرتبط بشق إيراد معيّن.
     */
    public static function likePattern(int $anchorId): string
    {
        return '%'.self::stamp($anchorId).'%';
    }
}
